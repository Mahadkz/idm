import json, re, sys
version = sys.argv[1]
meta = json.load(sys.stdin)
members = set(meta["workspace_members"])
rows = []
for p in meta["packages"]:
    if p["id"] in members:
        continue
    rows.append((p["name"], p["version"], p.get("license") or "", p.get("repository") or p.get("homepage") or "", p.get("license_file")))
rows.sort(key=lambda r: (r[0].lower(), r[1]))
COPYLEFT = re.compile(r"GPL|MPL|EPL|CDDL|OSL|CC-BY-SA|EUPL|SSPL", re.I)
def classify(expr):
    if not expr:
        return "UNKNOWN"
    # Any OR-alternative that is permissive makes the choice permissive.
    alts = [a.strip(" ()") for a in re.split(r"\s+OR\s+|/", expr)]
    if all(COPYLEFT.search(a) for a in alts if a):
        # LGPL/MPL are weak copyleft; GPL-3.0 compatible but flag for review.
        return "COPYLEFT"
    if any(COPYLEFT.search(a) for a in alts):
        return "OK (copyleft option available, permissive chosen)"
    return "OK"
flag = [(r, classify(r[2])) for r in rows]
bad = [(r, c) for r, c in flag if c in ("UNKNOWN", "COPYLEFT")]
print(f"# Third-party licenses\n\nXDM {version} is licensed under GPL-3.0 (see LICENSE). It is built from the Rust crates below, generated by `packaging/licenses.sh` from `cargo metadata` ({len(rows)} dependencies). Each crate remains under its own license; consult the crate repository for full texts.\n")
print("## Review flags\n")
if bad:
    print("Licenses that are copyleft-only or missing an SPDX expression (check compatibility with GPL-3.0):\n")
    for r, c in bad:
        print(f"- {r[0]} {r[1]}: `{r[2] or 'none declared'}` ({c})" + (f" - license file: {r[4]}" if r[4] else ""))
else:
    print("None: every dependency declares a permissive license (or a permissive alternative).")
print("\n## Dependencies\n\n| Crate | Version | License | Repository |\n|---|---|---|---|")
for r, c in flag:
    print(f"| {r[0]} | {r[1]} | {r[2] or 'UNKNOWN'} | {r[3]} |")
print(f"\nSummary: {len(rows)} crates, {len(bad)} flagged.", file=sys.stderr)
for r, c in bad:
    print(f"  FLAG {r[0]} {r[1]} {r[2] or 'none'} {c}", file=sys.stderr)
